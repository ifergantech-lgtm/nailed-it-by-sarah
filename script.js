const RTL_LANGS   = new Set(['he', 'ar']);
const LANG_LABELS = { he: 'עב', en: 'EN', fr: 'FR', es: 'ES', ar: 'عر' };


/* ===== SET LANGUAGE ===== */
function setLang(lang) {
  if (!T[lang]) return;

  const html = document.documentElement;
  html.lang = lang;
  html.dir  = RTL_LANGS.has(lang) ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = T[lang][key];
    if (val !== undefined) el.innerHTML = val;
  });

  document.getElementById('currentLangLabel').textContent = LANG_LABELS[lang] || lang;
  document.title = T[lang]['meta.title'] || document.title;

  renderReviews();
  localStorage.setItem('lang', lang);
}


